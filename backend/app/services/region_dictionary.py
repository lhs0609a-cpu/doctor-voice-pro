class _Ordered:
    """삽입 순서를 유지하는 중복 제거 목록."""

    __slots__ = ("_items", "_seen")

    def __init__(self) -> None:
        self._items: list[str] = []
        self._seen: set[str] = set()

    def add(self, name: str | None) -> None:
        if name and name not in self._seen:
            self._seen.add(name)
            self._items.append(name)

    def extend(self, names: Iterable[str]) -> None:
        for n in names:
            self.add(n)

    def list(self) -> list[str]:
        return list(self._items)


def _strip_suffix(token: str) -> str:
    """접미사(시/구/동/역 등)를 떼어낸 이름을 돌려준다. 사전에 있는 이름은 그대로."""
    token = _WS_RE.sub("", token)
    if not token or token in _KNOWN:
        return token
    m = _WARD_DIGIT_RE.search(token)
    if m and len(token) - len(m.group(0)) >= 2:
        token = token[: -len(m.group(0))]
        if token in _KNOWN:
            return token
    fallback: str | None = None
    for suf in _SUFFIXES:
        if token.endswith(suf) and len(token) - len(suf) >= 2:
            cand = token[: -len(suf)]
            if cand in _KNOWN:
                return cand
            if fallback is None:
                fallback = cand
    return fallback if fallback is not None else token


def _split_qualifier(text: str) -> tuple[str | None, str]:
    """
    "인천 논현", "서울시 강남구", "부산해운대" 같은 입력을 (상위 단위, 이름)으로 나눈다.
    상위 단위가 없으면 (None, 이름).
    """
    text = text.strip()
    if not text:
        return None, ""
    tokens = text.split()
    if len(tokens) >= 2:
        head = _strip_suffix(tokens[0])
        if head in _KNOWN:
            return head, "".join(tokens[1:])
        return None, "".join(tokens)
    token = tokens[0]
    stripped = _strip_suffix(token)
    if stripped in _KNOWN:
        return None, token
    # 띄어쓰기 없이 붙은 상위 단위: "부산해운대", "서울강남"
    for top in _TOP_NAMES:
        if token.startswith(top) and len(token) > len(top):
            rest = token[len(top):]
            if _strip_suffix(rest) in _KNOWN:
                return top, rest
    return None, token


def _matches_qualifier(info: dict, qualifier: str) -> bool:
    return qualifier == info["si"] or qualifier in info["parents"]


def _lookup(bare: str, qualifier: str | None) -> list[dict]:
    """정규화된 이름의 후보 목록. 상위 단위가 주어지면 그에 속한 후보를 우선한다."""
    infos = _NAME_INDEX.get(bare, [])
    if qualifier and infos:
        filtered = [i for i in infos if _matches_qualifier(i, qualifier)]
        if filtered:
            return filtered
    return infos


def _resolve(name: str) -> tuple[str, list[dict]]:
    """입력 문자열 -> (정규화 이름, 후보 목록)."""
    qualifier, raw = _split_qualifier(name)
    bare = _strip_suffix(raw)
    infos = _lookup(bare, qualifier)
    if infos and infos[0]["kind"] in ("si", "gu"):
        bare = infos[0]["name"]  # 방위 구는 표시 이름(부산중구)으로
    return bare, infos


def _is_area_like(info: dict) -> bool:
    return info["kind"] in ("area", "dong", "station")


def _same_place(primary: dict, other: dict) -> bool:
    """같은 이름의 두 지역 항목이 실제로 같은 곳(경계에 걸친 지역)인지 판단한다."""
    if not (_is_area_like(primary) and _is_area_like(other)):
        return False
    a, b = primary["unit"], other["unit"]
    if a == b:
        return True
    return b in _UNITS[a]["adjacent"] or a in _UNITS[b]["adjacent"]


def _area_adjacent(info: dict) -> list[str]:
    """지역 항목의 AREA_ADJ 연관 목록 (동명이역 키 우선)."""
    return AREA_ADJ.get(info["key"]) or AREA_ADJ.get(info["name"]) or []


def _unit_block(key: str, major: int = _LEVEL2_MAJOR) -> list[str]:
    """단위 이름 + 주요 지역 몇 개 (2단계 확장용)."""
    unit = _UNITS[key]
    block = [unit["name"]]
    if unit["parent"] is None:
        # 최상위 시·도는 하위 단위 이름을 대표로
        block.extend(_UNITS[c]["name"] for c in unit["children"][:major])
        block.extend(unit["areas"][:major])
    else:
        block.extend(unit["areas"][:major])
        block.extend(unit["stations"][:_LEVEL2_STATIONS])
    return block


