_LEVEL2_MAJOR = 6       # 2단계에서 인접 단위마다 가져올 주요 지역 수
_LEVEL2_STATIONS = 2    # 2단계에서 인접 단위마다 가져올 역 수


def _display_name(key: str) -> str:
    """단위 키 -> 표시 이름. 방위 구(중구 등)는 최상위 도시명을 앞에 붙인다."""
    parts = key.split("/")
    name = parts[-1]
    if name in _DIRECTIONAL_GU and len(parts) > 1:
        return parts[0] + name
    return name


def _build_units() -> dict[str, dict]:
    """UNITS 원본을 정규화한 내부 단위 사전으로 변환한다."""
    units: dict[str, dict] = {}
    for order, (key, spec) in enumerate(UNITS.items()):
        parts = key.split("/")
        units[key] = {
            "key": key,
            "name": _display_name(key),
            "raw": parts[-1],
            "kind": spec["kind"],
            "parent": "/".join(parts[:-1]) or None,
            "si": parts[0],
            "areas": list(spec.get("areas", [])),
            "stations": list(spec.get("stations", [])),
            "adjacent": [],
            "children": [],
            "order": order,
        }
    # 자식 연결
    for key, unit in units.items():
        if unit["parent"]:
            units[unit["parent"]]["children"].append(key)
    # 인접 참조 해석
    for key, unit in units.items():
        resolved: list[str] = []
        for ref in UNITS[key].get("adjacent", []):
            target = _resolve_ref(units, unit["parent"], ref)
            if target is None:
                raise ValueError(f"region_dictionary: 알 수 없는 인접 단위 {ref!r} (in {key})")
            if target != key and target not in resolved:
                resolved.append(target)
        unit["adjacent"] = resolved
    return units


def _resolve_ref(units: dict[str, dict], parent: str | None, ref: str) -> str | None:
    """인접 참조 문자열을 단위 키로 해석한다."""
    if "/" in ref:
        return ref if ref in units else None
    if parent and f"{parent}/{ref}" in units:
        return f"{parent}/{ref}"
    if ref in units:
        return ref
    return None


_UNITS: dict[str, dict] = _build_units()


def _unit_ancestors(unit: dict) -> list[str]:
    """단위의 상위 단위 표시 이름 목록 (최상위부터)."""
    names: list[str] = []
    parent = unit["parent"]
    while parent:
        names.insert(0, _UNITS[parent]["name"])
        parent = _UNITS[parent]["parent"]
    return names


def _area_kind(name: str, station: bool) -> str:
    if station:
        return "station"
    if name in _AREA_KIND_NAMES:
        return "area"
    return "dong"


def _build_index() -> dict[str, list[dict]]:
    """이름 -> 후보 정보 목록 인덱스를 만든다."""
    index: dict[str, list[dict]] = {}
    order = 0

    def add(name: str, info: dict) -> None:
        index.setdefault(name, []).append(info)

    for key, unit in _UNITS.items():
        ancestors = _unit_ancestors(unit)
        info = {
            "name": unit["name"],
            "kind": unit["kind"],
            "gu": unit["name"] if unit["kind"] == "gu" else None,
            "si": unit["si"],
            "parents": ancestors,
            "key": key,
            "unit": key,
            "_order": order,
        }
        order += 1
        add(unit["name"], info)
        if unit["raw"] != unit["name"]:
            add(unit["raw"], info)
        for station, names in ((False, unit["areas"]), (True, unit["stations"])):
            for area in names:
                add(area, {
                    "name": area,
                    "kind": _area_kind(area, station),
                    "gu": unit["name"] if unit["kind"] == "gu" else None,
                    "si": unit["si"],
                    "parents": ancestors + [unit["name"]],
                    "key": f"{key}/{area}",
                    "unit": key,
                    "_order": order,
                })
                order += 1

    for name, infos in index.items():
        primary_key = PRIMARY.get(name)
        infos.sort(key=lambda i: (
            0 if primary_key and i["key"] == primary_key else 1,
            _KIND_RANK.get(i["kind"], 9),
            i["_order"],
        ))
    return index


_NAME_INDEX: dict[str, list[dict]] = _build_index()
_KNOWN: frozenset[str] = frozenset(_NAME_INDEX)
_TOP_NAMES: tuple[str, ...] = tuple(k for k, u in _UNITS.items() if u["parent"] is None)


