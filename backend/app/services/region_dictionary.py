def normalize_region(name: str) -> str:
    """
    지역명을 키워드용 기본형으로 정규화한다.

    - 앞뒤/중간 공백 제거
    - 접미사 처리: "강남구"->"강남", "역삼동"->"역삼", "역삼역"->"역삼",
      "역삼1동"->"역삼", "서울특별시"->"서울"
    - 상위 단위 제거: "서울 강남"->"강남", "인천 논현"->"논현"
    - 사전에 있는 이름은 그대로 둔다: "위례"->"위례", "중동"->"중동"
    - 방위 구는 도시명이 붙은 표시 이름으로: "부산 중구"->"부산중구", "중구"->"서울중구"
    - 사전에 없는 이름은 접미사만 떼어 돌려준다 (빈 문자열 입력은 빈 문자열)
    """
    if not name or not name.strip():
        return ""
    bare, _ = _resolve(name)
    return bare


def expand_region(name: str, level: int = 1, limit: int = 30) -> list[str]:
    """
    기준 지역명을 인접·연관 지역명 목록으로 확장한다.

    level 0: [정규화된 이름] 만
    level 1: 이름 + 같은 구 안의 동/역 + 직접 인접한 동/역/구 이름 (대략 8~20개)
    level 2: level 1 + 인접 구(시)와 그 주요 동/역 (대략 20~40개)

    결과는 중복 제거, 관련도 순(자기 자신 -> 같은 구 -> 인접), limit 개로 자른다.
    사전에 없는 이름은 [정규화된 이름] 만 돌려주며 절대 빈 목록을 돌려주지 않는다.
    첫 번째 항목은 항상 정규화된 입력이다.

    동명이역: "논현"은 서울 강남 논현으로 확장된다. "인천 논현", "울산 성남",
    "경기 광주" 처럼 상위 단위를 앞에 붙이면 해당 지역으로 확장된다.
    같은 이름이 서로 인접한 단위에 걸쳐 있으면(위례: 송파/성남/하남, 첨단: 북구/광산)
    하나의 지역으로 보고 모든 쪽의 정보를 합친다.
    """
    bare, infos = _resolve(name)
    if not bare:
        bare = _WS_RE.sub("", name or "")
    out = _Ordered()
    out.add(bare)
    if limit is None or limit < 1:
        limit = 1
    if not infos or level <= 0:
        return out.list()[:limit] or [bare]

    primary = infos[0]
    group = [primary] + [i for i in infos[1:] if _same_place(primary, i)]

    if _is_area_like(primary):
        # 1단계: 직접 연관 지역 -> 소속 단위 -> 같은 단위 안의 동/역 -> 소속 단위의 인접 단위
        out.extend(_area_adjacent(primary))
        for info in group:
            out.add(_UNITS[info["unit"]]["name"])
        if len(group) == 1:
            unit = _UNITS[primary["unit"]]
            out.extend(unit["areas"])
            out.extend(unit["stations"])
        else:
            # 경계에 걸친 지역(위례 등): 각 소속 단위의 주요 지역을 번갈아 넣어
            # 한쪽 단위가 결과를 독점하지 않게 한다
            for info in group:
                unit = _UNITS[info["unit"]]
                out.extend(unit["areas"][:_LEVEL2_MAJOR])
                out.extend(unit["stations"][:_LEVEL2_STATIONS])
            for info in group:
                unit = _UNITS[info["unit"]]
                out.extend(unit["areas"])
                out.extend(unit["stations"])
        adjacent_keys: list[str] = []
        for info in group:
            for adj in _UNITS[info["unit"]]["adjacent"]:
                if adj not in adjacent_keys:
                    adjacent_keys.append(adj)
        out.extend(_UNITS[k]["name"] for k in adjacent_keys)
        if level >= 2:
            # 2단계: 연관 지역의 소속 단위 + 인접 단위의 주요 동/역
            for adj_name in _area_adjacent(primary):
                for cand in _NAME_INDEX.get(adj_name, [])[:1]:
                    if _is_area_like(cand) and cand["unit"] not in adjacent_keys:
                        out.add(_UNITS[cand["unit"]]["name"])
            for k in adjacent_keys:
                out.extend(_unit_block(k))
    else:
        unit = _UNITS[primary["unit"]]
        if unit["parent"] is None:
            # 최상위 시·도: 하위 단위 이름 -> 직할 지역 -> 인접 시·도
            out.extend(_UNITS[c]["name"] for c in unit["children"])
            out.extend(unit["areas"])
            out.extend(unit["stations"])
            out.extend(_area_adjacent(primary))
            out.extend(_UNITS[k]["name"] for k in unit["adjacent"])
            if level >= 2:
                for c in unit["children"]:
                    out.extend(_UNITS[c]["areas"][:3])
                for k in unit["adjacent"]:
                    out.extend(_unit_block(k))
        else:
            # 구 / 시: 자기 동/역 -> 연관 지역 -> 인접 단위 이름
            out.extend(unit["areas"])
            out.extend(unit["stations"])
            out.extend(_area_adjacent(primary))
            out.extend(_UNITS[k]["name"] for k in unit["adjacent"])
            if level >= 2:
                for k in unit["adjacent"]:
                    out.extend(_unit_block(k))
                for c in unit["children"]:
                    out.add(_UNITS[c]["name"])

    return out.list()[:limit]


def region_info(name: str) -> dict | None:
    """
    지역명의 사전 정보를 돌려준다. 없으면 None.

    반환 예: {"name": "역삼", "kind": "dong", "gu": "강남", "si": "서울",
             "parents": ["서울", "강남"], "key": "서울/강남/역삼"}

    - kind: "si"(시·도·광역시·일반시) | "gu" | "area"(신도시·상권) | "dong" | "station"
    - gu: 소속 구 이름 (구가 아닌 시 소속이면 None)
    - si: 최상위 시·도 이름 ("서울", "경기", "부산", "충남" ...)
    - parents: 최상위부터 직속 상위까지의 이름 목록
    - key: 사전 내부 키 (동명이역 구분용)

    동명이역은 우선순위가 가장 높은 첫 번째 후보를 돌려준다.
    "인천 논현" 처럼 상위 단위를 붙이면 그 후보를 돌려준다.
    """
    if not name or not name.strip():
        return None
    _, infos = _resolve(name)
    if not infos:
        return None
    info = infos[0]
    return {
        "name": info["name"],
        "kind": info["kind"],
        "gu": info["gu"],
        "si": info["si"],
        "parents": list(info["parents"]),
        "key": info["key"],
    }


def known_regions() -> list[str]:
    """사전에 등록된 모든 지역 이름 (표시 이름 기준, 등록 순서, 중복 없음)."""
    out = _Ordered()
    for unit in _UNITS.values():
        out.add(unit["name"])
        out.extend(unit["areas"])
        out.extend(unit["stations"])
    return out.list()


def combine(
    regions: list[str],
    diseases: list[str],
    suffixes: list[str] | None = None,
    max_items: int = 400,
) -> list[dict]:
    """
    지역명 x 질환명 x 접미사 조합으로 키워드 목록을 만든다.

    반환: [{"keyword": "강남아토피한의원", "region": "강남",
            "disease": "아토피", "suffix": "한의원"}, ...]

    - 지역 우선(region-major) 순서, 같은 지역 안에서는 질환 순, 접미사는 "" 가 먼저
    - 키워드 기준 중복 제거, 공백 제거, max_items 개로 자른다
    - suffixes 가 None 이면 SUFFIX_DEFAULTS 사용
    """
    if suffixes is None:
        suffixes = list(SUFFIX_DEFAULTS)
    suffix_list: list[str] = []
    for s in suffixes:
        s = _WS_RE.sub("", s or "")
        if s not in suffix_list:
            suffix_list.append(s)
    if "" in suffix_list:
        suffix_list.remove("")
        suffix_list.insert(0, "")
    if not suffix_list:
        suffix_list = [""]

    results: list[dict] = []
    seen: set[str] = set()
    if max_items is None or max_items < 1:
        return results
    for region in regions:
        region = _WS_RE.sub("", region or "")
        if not region:
            continue
        for disease in diseases:
            disease = _WS_RE.sub("", disease or "")
            if not disease:
                continue
            for suffix in suffix_list:
                keyword = f"{region}{disease}{suffix}"
                if keyword in seen:
                    continue
                seen.add(keyword)
                results.append({
                    "keyword": keyword,
                    "region": region,
                    "disease": disease,
                    "suffix": suffix,
                })
                if len(results) >= max_items:
                    return results
    return results


